-- Version 6: owner values shown on an ownership row are independent snapshots.
-- A normalized owner can be linked to more than one ownership.  Editing one
-- flat desktop row must not silently change the name, identity or address shown
-- on another row, even when both rows belong to the same parcel.

ALTER TABLE ownerships ADD COLUMN IF NOT EXISTS owner_name_override TEXT;
ALTER TABLE ownerships ADD COLUMN IF NOT EXISTS external_id_override TEXT;
ALTER TABLE ownerships ADD COLUMN IF NOT EXISTS address_override TEXT;

UPDATE ownerships ownership
SET owner_name_override = COALESCE(ownership.owner_name_override, owner.owner_name),
    external_id_override = COALESCE(ownership.external_id_override, owner.external_id),
    address_override = COALESCE(ownership.address_override, owner.address)
FROM owners owner
WHERE owner.id = ownership.owner_id
  AND (
      ownership.owner_name_override IS NULL
      OR ownership.external_id_override IS NULL
      OR ownership.address_override IS NULL
  );

