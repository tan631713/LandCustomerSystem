CREATE TABLE IF NOT EXISTS field_visit_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date DATE NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'planned'
        CHECK (status IN ('draft', 'planned', 'in_progress', 'completed', 'cancelled')),
    start_latitude DOUBLE PRECISION
        CHECK (start_latitude BETWEEN -90 AND 90),
    start_longitude DOUBLE PRECISION
        CHECK (start_longitude BETWEEN -180 AND 180),
    total_distance_km NUMERIC(14, 3)
        CHECK (total_distance_km IS NULL OR total_distance_km >= 0),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (start_latitude IS NULL AND start_longitude IS NULL)
        OR
        (start_latitude IS NOT NULL AND start_longitude IS NOT NULL)
    )
);

