CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT,
    role TEXT NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin', 'editor', 'viewer')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    encryption_salt TEXT NOT NULL,
    wrapped_data_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS owners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key TEXT NOT NULL UNIQUE,
    owner_name TEXT NOT NULL,
    external_id TEXT,
    address TEXT,
    phone TEXT,
    category TEXT,
    development_status TEXT,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS lands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    land_key TEXT NOT NULL UNIQUE,
    district TEXT NOT NULL DEFAULT '',
    section TEXT NOT NULL DEFAULT '',
    land_number TEXT NOT NULL DEFAULT '',
    area TEXT,
    declared_value TEXT,
    zoning TEXT,
    location_note TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (district, section, land_number)
);

CREATE TABLE IF NOT EXISTS ownerships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_customer_id BIGINT UNIQUE,
    owner_id BIGINT NOT NULL REFERENCES owners(id) ON DELETE RESTRICT,
    land_id BIGINT NOT NULL REFERENCES lands(id) ON DELETE RESTRICT,
    registration_order TEXT,
    numerator TEXT,
    denominator TEXT,
    ping TEXT,
    total_declared_value TEXT,
    registration_reason TEXT,
    note TEXT,
    visit_log TEXT,
    name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ownerships_owner_id ON ownerships(owner_id);
CREATE INDEX IF NOT EXISTS idx_ownerships_land_id ON ownerships(land_id);
CREATE INDEX IF NOT EXISTS idx_lands_location ON lands(district, section, land_number);

CREATE TABLE IF NOT EXISTS contact_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_contact_log_id BIGINT UNIQUE,
    ownership_id BIGINT NOT NULL REFERENCES ownerships(id) ON DELETE CASCADE,
    contact_date DATE,
    method TEXT,
    result TEXT,
    next_follow_up DATE,
    note TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_contact_logs_ownership
ON contact_logs(ownership_id, contact_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS follow_up_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ownership_id BIGINT NOT NULL UNIQUE REFERENCES ownerships(id) ON DELETE CASCADE,
    due_date DATE,
    status TEXT NOT NULL DEFAULT '未處理',
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT '進行中',
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    due_date DATE,
    priority TEXT NOT NULL DEFAULT '一般',
    next_action TEXT,
    estimated_area NUMERIC,
    estimated_value NUMERIC,
    note TEXT,
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS project_owners (
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, owner_id)
);

CREATE TABLE IF NOT EXISTS project_lands (
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    land_id BIGINT NOT NULL REFERENCES lands(id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, land_id)
);

CREATE TABLE IF NOT EXISTS import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file_name TEXT NOT NULL,
    total_rows INTEGER NOT NULL DEFAULT 0,
    success_rows INTEGER NOT NULL DEFAULT 0,
    duplicate_rows INTEGER NOT NULL DEFAULT 0,
    failed_rows INTEGER NOT NULL DEFAULT 0,
    imported_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS import_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
    row_number INTEGER NOT NULL,
    raw_values JSONB NOT NULL,
    processing_status TEXT NOT NULL DEFAULT 'pending',
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (batch_id, row_number)
);

CREATE TABLE IF NOT EXISTS attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES owners(id) ON DELETE CASCADE,
    land_id BIGINT REFERENCES lands(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    storage_path TEXT NOT NULL,
    original_name TEXT NOT NULL,
    media_type TEXT,
    size_bytes BIGINT,
    sha256 TEXT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (owner_id IS NOT NULL OR land_id IS NOT NULL OR project_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    actor TEXT,
    action_type TEXT NOT NULL,
    entity_type TEXT,
    entity_id BIGINT,
    summary TEXT NOT NULL,
    detail JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

