-- PostgreSQL schema for the self-hosted Windows/iPhone system.
-- Sensitive owner values keep the existing enc:v1: Fernet ciphertext format.

CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

